const LanguageContext = createContext<LanguageContextType>({
  lang: "hi",
  setLang: () => {},
  toggleLang: () => {},
  isHindi: true,
  t: () => "",
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>("hi");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("annadata_language") as Language | null;
      if (saved === "hi" || saved === "en") {
        setLangState(saved);
      }
    } catch {
      // ignore SSR or storage access errors
    }
  }, []);

  const setLang = (newLang: Language) => {
    setLangState(newLang);
    try {
      localStorage.setItem("annadata_language", newLang);
    } catch {
      // ignore
    }
  };

  const toggleLang = () => {
    setLang(lang === "hi" ? "en" : "hi");
  };

  const t = (section: string, key: string): string => {
    const sec = translations[lang]?.[section];
    if (sec && sec[key]) {
      return sec[key];
    }
    return translations.hi?.[section]?.[key] || key;
  };

  return (
    <LanguageContext.Provider
      value={{
        lang,
        setLang,
        toggleLang,
        isHindi: lang === "hi",
        t,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
